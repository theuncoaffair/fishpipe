package com.theuncoaffair.fishpipe.data;

import java.io.Serializable;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public final class MediaItem implements Serializable {
    private static final long serialVersionUID = 1L;
    private static final Pattern HASHTAG = Pattern.compile("#([\\p{L}\\p{N}_]+)");
    private static final Pattern SYNTHETIC_TITLE = Pattern.compile(
            "(?i)^(tiktok|douyin)\\s+[0-9]+$");

    public String id = "";
    public String title = "";
    public String author = "";
    public String coverUrl = "";
    public String videoUrl = "";
    public String videoHdUrl = "";
    public String videoWmUrl = "";
    public String musicUrl = "";
    public String musicTitle = "";
    public String musicAuthor = "";
    public String musicCoverUrl = "";
    public String pageUrl = "";
    public String source = "";
    public String authorId = "";
    public String authorAvatar = "";
    public String region = "";
    public String musicId = "";
    public boolean story;
    public boolean slideshow;
    public long createTime;
    public long durationSeconds;
    public long playCount;
    public long diggCount;
    public long commentCount;
    public long shareCount;
    public long collectCount;
    public List<String> images = new ArrayList<>();
    public List<CaptionTrack> captions = new ArrayList<>();

    public boolean hasVideo() {
        return notEmpty(videoUrl) || notEmpty(videoHdUrl) || notEmpty(videoWmUrl);
    }

    public boolean hasMusic() {
        return notEmpty(musicUrl);
    }

    public boolean hasCover() {
        return notEmpty(coverUrl);
    }

    public boolean hasImages() {
        return images != null && !images.isEmpty();
    }

    public boolean hasCaptions() {
        if (captions == null) return false;
        for (CaptionTrack track : captions) {
            if (track != null && track.usable()) return true;
        }
        return false;
    }

    public CaptionTrack bestCaption(Locale locale) {
        if (captions == null || captions.isEmpty()) return null;
        String language = locale == null ? "" : locale.getLanguage();
        CaptionTrack best = null;
        int bestScore = Integer.MIN_VALUE;
        for (CaptionTrack track : captions) {
            if (track == null || !track.usable()) continue;
            int score = 0;
            if (track.autoGenerated) score += 20;
            if (MediaItem.notEmpty(language) && language.equalsIgnoreCase(track.languageCode)) {
                score += 60;
            } else if (MediaItem.notEmpty(language) && track.languageCode != null
                    && track.languageCode.toLowerCase(Locale.US).startsWith(
                    language.toLowerCase(Locale.US))) {
                score += 40;
            }
            if ("en".equalsIgnoreCase(track.languageCode)) score += 10;
            if (track.format != null && track.format.toLowerCase(Locale.US).contains("vtt")) score += 2;
            if (score > bestScore) {
                bestScore = score;
                best = track;
            }
        }
        return best;
    }

    public boolean hasContent() {
        return hasVideo() || hasImages();
    }

    public String bestVideo(boolean preferHd) {
        if (preferHd && notEmpty(videoHdUrl)) return videoHdUrl;
        if (notEmpty(videoUrl)) return videoUrl;
        if (notEmpty(videoHdUrl)) return videoHdUrl;
        return videoWmUrl;
    }

    public String captionFromTitle() {
        return captionForDisplay(title);
    }

    public String hashtagsFromTitle() {
        return hashtagsOf(title);
    }

    public static String captionForDisplay(String text) {
        String caption = captionOf(text);
        return isSyntheticTitle(caption) ? "" : caption;
    }

    public static boolean isSyntheticTitle(String text) {
        return text != null && SYNTHETIC_TITLE.matcher(text.trim()).matches();
    }

    public static String captionOf(String text) {
        if (text == null || text.trim().isEmpty()) return "";
        String cleaned = HASHTAG.matcher(text).replaceAll(" ");
        cleaned = cleaned.replaceAll("[\\t\\x0B\\f\\r ]+", " ");
        cleaned = cleaned.replaceAll("(?m) *\\n *", "\n");
        cleaned = cleaned.replaceAll("\\n{3,}", "\n\n");
        cleaned = cleaned.replaceAll(" +([,.!?;:])", "$1");
        return cleaned.trim();
    }

    public static String hashtagsOf(String text) {
        if (text == null || text.isEmpty()) return "";
        Map<String, String> unique = new LinkedHashMap<>();
        Matcher matcher = HASHTAG.matcher(text);
        while (matcher.find()) {
            String tag = matcher.group();
            if (tag.length() <= 1) continue;
            String key = tag.toLowerCase(Locale.US);
            if (!unique.containsKey(key)) unique.put(key, tag);
        }
        StringBuilder out = new StringBuilder();
        for (String tag : unique.values()) {
            if (out.length() > 0) out.append(' ');
            out.append(tag);
        }
        return out.toString();
    }

    public static boolean notEmpty(String value) {
        return value != null && !value.trim().isEmpty();
    }

    public static String orEmpty(String value) {
        return value == null ? "" : value;
    }

    public static long seconds(long value) {
        return value > 100000000000L ? value / 1000L : value;
    }

    public static final class CaptionTrack implements Serializable {
        private static final long serialVersionUID = 1L;

        public String url = "";
        public String language = "";
        public String languageCode = "";
        public String format = "";
        public String name = "";
        public boolean autoGenerated;

        public boolean usable() {
            return notEmpty(url) && (url.startsWith("http://") || url.startsWith("https://"));
        }
    }
}
